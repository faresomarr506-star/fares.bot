// مبدّل اللغة
function applyLanguage(lang) {
  const dict = window.I18N[lang] || window.I18N.ar;
  document.documentElement.lang = lang;
  document.documentElement.dir = dict.dir;
  document.body.classList.toggle('rtl', dict.dir === 'rtl');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] != null) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key] != null) el.setAttribute('placeholder', dict[key]);
  });
  try { localStorage.setItem('fares_lang', lang); } catch (_) {}
  document.querySelectorAll('[data-lang-btn]').forEach((b) => {
    b.classList.toggle('active', b.getAttribute('data-lang-btn') === lang);
  });
}

window.applyLanguage = applyLanguage;
window.switchLanguage = function (lang) { applyLanguage(lang); };

document.addEventListener('DOMContentLoaded', () => {
  let saved = 'ar';
  try { saved = localStorage.getItem('fares_lang') || 'ar'; } catch (_) {}
  applyLanguage(saved);
});
